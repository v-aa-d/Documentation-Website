function wave(a) {
  switch (waveType) {
    case 'triangle': return asin(sin(a)) / 90;
    case 'pulse':    return sin(a) >= 0 ? 1 : -1;
    case 'sawtooth': return (((a % 360) + 360) % 360) / 180 - 1;
    case 'complex':  return (sin(a) + sin(2*a)*0.5 + sin(3*a)*0.33 + sin(5*a)*0.2) / 2.03;
    default:         return sin(a);
  }
}

function setup() {
  createCanvas(windowWidth, windowHeight);
  angleMode(DEGREES);

  const sel = createSelect();
  ['Sine', 'Triangle', 'Pulse', 'Sawtooth', 'Complex'].forEach(w => sel.option(w));
  sel.changed(() => { waveType = sel.value().toLowerCase(); });
}

function keyPressed() {
  if (keyCode === BACKSPACE) { typed = typed.slice(0, -1); scrollX = 0; return false; }
  if (keyCode === ESCAPE)    { typed = ''; scrollX = 0; return false; }
  const c = key.toUpperCase();
  if (key.length === 1 && FONT[c]) typed += c;
  return false;
}

function isLit(gx, gy) {
  if (!typed) return false;
  const totalW = typed.length * 6 - 1;
  const oy = floor((TILE - 7) / 2);
  const cy = gy - oy;
  if (cy < 0 || cy >= 7) return false;

  // centered when fits, scrolling when overflows
  const px = totalW <= TILE
    ? gx - floor((TILE - totalW) / 2)
    : gx - TILE + floor(scrollX);

  for (let i = 0; i < typed.length; i++) {
    const cx = px - i * 6;
    const p = FONT[typed[i]];
    if (p && cx >= 0 && cx < 5 && p[cy][cx] === '1') return true;
  }
  return false;
}

function draw() {
  const wid = width, hei = height;
  background(0);

  if (typed) {
    const totalW = typed.length * 6 - 1;
    if (totalW > TILE) scrollX = (scrollX + 0.05) % (TILE + totalW);
  }

  push();
  translate(floor(wave(m) * -XSPD) / 100, floor(wave(m + 90) * -YSPD) / 100);
  for (let x = 0; x < TILE; x++) {
    for (let y = 0; y < TILE; y++) {
      fill(typed && !isLit(x, y) ? 20 : 255);
      noStroke();
      const xx = x * (wid / TILE);
      const n = floor(wave(m + x * UPP) * XSPD) / 100;
      const o = floor(wave(m + (x + 1) * UPP) * XSPD) / 100;
      const p = floor(wave(m + y * UPP + 90) * YSPD) / 100;
      const q = floor(wave(m + (y + 1) * UPP + 90) * YSPD) / 100;
      const yy = y * (hei / TILE);
      rectMode(CORNERS);
      rect(xx + n, yy + p, xx + o - 1 + wid / TILE, yy + q - 1 + hei / TILE);
    }
  }
  pop();
  m++;
}
