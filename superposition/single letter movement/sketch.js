function isLit(gx, gy) {
  if (!showChar || !FONT[showChar]) return false;
  const cw = 5, ch = 7;
  const ox = floor((tile - cw) / 2);
  const oy = floor((tile - ch) / 2);
  const cx = gx - ox;
  const cy = gy - oy;
  if (cx < 0 || cx >= cw || cy < 0 || cy >= ch) return false;
  return FONT[showChar][cy][cx] === '1';
}

function keyPressed() {
  if (keyCode === BACKSPACE) {
    showChar = '';
    return false;
  }
  if (keyCode === ESCAPE) {
    showChar = '';
    return false;
  }
  if (key.length === 1) {
    const c = key.toUpperCase();
    if (FONT[c] !== undefined) {
      showChar = c;
    }
  }
  return false;
}

function draw() {
  let wid = width * 0.8;
  let hei = height * 0.8;

  background(0, 0, 0);
  angleMode(DEGREES);
  translate(width / 10, height / 10);
  push();
  translate(floor(1 + sin(m) * -xspd) / 100, floor(1 + cos(m) * -yspd) / 100);

  for (let x = 0; x < tile; x++) {
    for (let y = 0; y < tile; y++) {
      let lit = isLit(x, y);
      noStroke();

      if (showChar) {
        if (lit) {
          fill(0, 0, 100, 100); // white
        } else {
          fill(0, 0, 8, 100); // near-black
        }
      } else {
        fill(0, 0, 100, 100); // original white
      }

      let xx = x * (wid / tile);
      let n = floor(sin(m + x * upp) * xspd) / 100;
      let o = floor(sin(m + (x + 1) * upp) * xspd) / 100;
      let p = floor(cos(m + y * upp) * yspd) / 100;
      let q = floor(cos(m + (y + 1) * upp) * yspd) / 100;
      let yy = y * (hei / tile);
      rectMode(CORNERS);
      rect(xx + n, yy + p, xx + o - 1 + wid / tile, yy + q - 1 + hei / tile);
    }
  }

  pop();

  // Hint text
  if (!showChar) {
    colorMode(RGB);
    fill(255, 255, 255, 60);
    noStroke();
    textSize(13);
    textAlign(CENTER);
    text('type a key', width / 2, height - 20);
    colorMode(HSB, 360, 100, 100, 100);
  }

  if (flashAlpha > 0) flashAlpha -= 3;
  m += 1;
}
